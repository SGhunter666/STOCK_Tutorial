export function getCompany(ticker) {
  return COMPANIES.find((c) => c.ticker === ticker) || null;
}

export function companyNameKey(ticker) {
  return `company.${ticker}.name`;
}

export function companyDescKey(ticker) {
  return `company.${ticker}.desc`;
}

export function marketCapFor(company, price) {
  return company.sharesOutstanding * price;
}

export function fundamentalsFor(company, price) {
  const eps = company.netIncome / company.sharesOutstanding;
  const shares = company.sharesOutstanding;
  return {
    sharesOutstanding: shares,
    marketCap: shares * price,
    revenue: company.revenue,
    netIncome: company.netIncome,
    eps,
    pe: eps > 0 ? price / eps : null,
    pb: price / company.bookValuePerShare,
    dividendYield: company.dividendYield,
  };
}
